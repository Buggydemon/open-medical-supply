const errors = [];
page.on('pageerror', error => errors.push(error.message));
const results = { base, checks: [], accessibility: [] };
const pass = label => results.checks.push(label);
async function audit(label) {
  const data = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze();
  results.accessibility.push({ label, violations: data.violations.map(v => ({ id: v.id, impact: v.impact, nodes: v.nodes.map(n => ({ target: n.target, summary: n.failureSummary })) })) });
}
async function noOverflow(label) {
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, label);
  pass(label);
}
